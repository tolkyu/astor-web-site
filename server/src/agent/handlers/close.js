/**
 * close_conversation — агент каже, що розмова закінчилась.
 *
 * Сам статус виставляється тут, а запис про закриття (і прохання оцінити
 * спілкування) робить канал — telegramAgent або chatRoutes — уже після
 * того, як модель доробила свій хід. Причина в порядку: customerId часто
 * з'являється в тому самому ході, що й закриття, бо агент викликає
 * save_customer і close_conversation поруч. Запиши ми закриття звідси —
 * оцінка лягла б без клієнта, а саме за клієнтом етап B рахує 90 днів
 * між посиланнями на відгук.
 *
 * Інструмент без аргументів: закривати можна лише той діалог, у якому
 * модель зараз говорить, і передавати його id їй нема сенсу — вона його
 * не бачить (див. handlers/customer.js про id в аргументах).
 */
export async function closeConversation(input, ctx) {
  ctx.conversation.status = 'closed';

  return {
    closed: true,
    message:
      'Діалог закрито. Попрощайся одним коротким реченням. Нічого більше не питай ' +
      'і не пропонуй — далі клієнт побачить прохання оцінити спілкування.',
  };
}
